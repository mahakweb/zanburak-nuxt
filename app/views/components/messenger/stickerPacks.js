const CUSTOM_PACKS_KEY = 'messenger-custom-sticker-packs';
const INSTALLED_PACKS_KEY = 'messenger-installed-sticker-packs';
const PACK_ORDER_KEY = 'messenger-sticker-pack-order';

export function loadCustomStickerPacks() {
  try {
    const raw = localStorage.getItem(CUSTOM_PACKS_KEY);
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveCustomStickerPacks(packs) {
  try {
    localStorage.setItem(CUSTOM_PACKS_KEY, JSON.stringify(packs || []));
  } catch {
    /* quota */
  }
}

export function loadInstalledPackIds() {
  try {
    const raw = localStorage.getItem(INSTALLED_PACKS_KEY);
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed.map(String) : [];
  } catch {
    return [];
  }
}

export function saveInstalledPackIds(ids) {
  try {
    localStorage.setItem(INSTALLED_PACKS_KEY, JSON.stringify([...(new Set(ids || []))]));
  } catch {
    /* quota */
  }
}

export function loadPackOrder() {
  try {
    const raw = localStorage.getItem(PACK_ORDER_KEY);
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed.map(String) : [];
  } catch {
    return [];
  }
}

export function savePackOrder(ids) {
  try {
    localStorage.setItem(PACK_ORDER_KEY, JSON.stringify([...(ids || [])].map(String)));
  } catch {
    /* quota */
  }
}

/** Persist sticker pack tab order (excludes the synthetic "recent" row). */
export function reorderStickerPacks(orderedIds) {
  if (!Array.isArray(orderedIds)) return;
  savePackOrder(orderedIds.map(String).filter((id) => id && id !== 'recent'));
}

export function isPackInstalled(packId) {
  if (!packId) return false;
  const id = String(packId);
  if (loadInstalledPackIds().includes(id)) return true;
  // Local-only packs (not synced from server) count as installed while present.
  const local = loadCustomStickerPacks().find((p) => String(p.id) === id);
  return !!(local && !local.remote);
}

export function installPack(pack) {
  if (!pack?.id) return false;
  const id = String(pack.id);
  if (BUILTIN_STICKER_PACKS.some((p) => p.id === pack.id)) {
    const ids = loadInstalledPackIds();
    if (!ids.includes(id)) {
      saveInstalledPackIds([id, ...ids]);
    }
    return true;
  }
  const packs = loadCustomStickerPacks();
  const existing = packs.find((p) => String(p.id) === id);
  if (!existing) {
    packs.unshift({
      id: pack.id,
      title: pack.title || 'Pack',
      titleFa: pack.titleFa || pack.title || 'پک',
      icon: pack.icon || pack.stickers?.[0]?.emoji || '⭐',
      stickers: (pack.stickers || []).map((s) => ({ ...s })),
      custom: true,
      remote: !!pack.remote,
    });
    saveCustomStickerPacks(packs);
  } else {
    // Refresh sticker list / metadata when re-installing a cached remote pack.
    existing.title = pack.title || existing.title;
    existing.titleFa = pack.titleFa || existing.titleFa;
    existing.icon = pack.icon || existing.icon;
    if (Array.isArray(pack.stickers) && pack.stickers.length) {
      existing.stickers = pack.stickers.map((s) => ({ ...s }));
    }
    existing.remote = existing.remote || !!pack.remote;
    saveCustomStickerPacks(packs);
  }
  const ids = loadInstalledPackIds();
  if (!ids.includes(id)) {
    saveInstalledPackIds([id, ...ids]);
  }
  return true;
}

export function uninstallPack(packId) {
  if (!packId) return;
  const id = String(packId);
  saveInstalledPackIds(loadInstalledPackIds().filter((x) => x !== id));
  // Drop local-only packs entirely; keep remote pack cache for chat preview sheets.
  const packs = loadCustomStickerPacks();
  const next = packs.filter((p) => {
    if (String(p.id) !== id) return true;
    return !!p.remote;
  });
  if (next.length !== packs.length) {
    saveCustomStickerPacks(next);
  }
}

export function deleteCustomPack(packId) {
  uninstallPack(packId);
}

/** True when id is a server pack/sticker UUID (not local pack_ / cu_ ids). */
export function isServerPackId(id) {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(String(id || ''));
}

/** Add an image into a specific custom/remote pack (local cache). */
export function addStickerToPack(packId, dataUrl, emoji = '⭐') {
  if (!packId || !dataUrl) return null;
  const packs = loadCustomStickerPacks();
  let pack = packs.find((p) => p.id === packId);
  if (!pack) {
    return addCustomSticker(dataUrl, emoji);
  }
  const sticker = {
    id: `cu_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`,
    kind: 'image',
    src: dataUrl,
    emoji: emoji || '⭐',
  };
  pack.stickers = [sticker, ...(pack.stickers || [])].slice(0, 120);
  pack.icon = pack.stickers[0]?.emoji || pack.icon;
  saveCustomStickerPacks(packs);
  return { sticker, pack };
}

/** Add an image (data URL) into the user custom pack. */
export function addCustomSticker(dataUrl, emoji = '⭐') {
  if (!dataUrl) return null;
  const packs = loadCustomStickerPacks();
  let pack = packs.find((p) => p.id === 'custom');
  if (!pack) {
    pack = {
      id: 'custom',
      title: 'My stickers',
      titleFa: 'استیکرهای من',
      icon: '⭐',
      stickers: [],
      custom: true,
    };
    packs.unshift(pack);
  }
  const sticker = {
    id: `cu_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`,
    kind: 'image',
    src: dataUrl,
    emoji,
  };
  pack.stickers = [sticker, ...(pack.stickers || [])].slice(0, 120);
  pack.icon = pack.stickers[0]?.emoji || pack.icon;
  saveCustomStickerPacks(packs);
  return { sticker, pack };
}

/** Create a new custom pack from image data URLs. */
export function createCustomPack({ title, titleFa, stickers = [] } = {}) {
  const id = `pack_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`;
  const list = (stickers || []).map((s, i) => ({
    id: s.id || `${id}_${i}`,
    kind: s.kind || (s.src ? 'image' : 'emoji'),
    src: s.src || null,
    emoji: s.emoji || '⭐',
  })).filter((s) => s.src || s.emoji);
  if (!list.length) return null;
  const pack = {
    id,
    title: title || 'My pack',
    titleFa: titleFa || title || 'پک من',
    icon: list[0].emoji || '⭐',
    stickers: list,
    custom: true,
  };
  const packs = loadCustomStickerPacks();
  packs.unshift(pack);
  saveCustomStickerPacks(packs);
  return pack;
}

export function updateCustomSticker(packId, stickerId, patch = {}) {
  const packs = loadCustomStickerPacks();
  const pack = packs.find((p) => p.id === packId);
  if (!pack) return null;
  const idx = (pack.stickers || []).findIndex((s) => s.id === stickerId);
  if (idx < 0) return null;
  pack.stickers[idx] = { ...pack.stickers[idx], ...patch };
  saveCustomStickerPacks(packs);
  return pack.stickers[idx];
}

export function removeCustomSticker(packId, stickerId) {
  const packs = loadCustomStickerPacks();
  const pack = packs.find((p) => p.id === packId);
  if (!pack) return false;
  pack.stickers = (pack.stickers || []).filter((s) => s.id !== stickerId);
  if (!pack.stickers.length && pack.id !== 'custom') {
    saveCustomStickerPacks(packs.filter((p) => p.id !== packId));
  } else {
    saveCustomStickerPacks(packs);
  }
  return true;
}

export function findPackById(packId) {
  if (!packId) return null;
  const id = String(packId);
  const custom = loadCustomStickerPacks().find((p) => String(p.id) === id);
  if (custom) return { ...custom };
  const builtin = BUILTIN_STICKER_PACKS.find((p) => String(p.id) === id);
  if (builtin) return { ...builtin };
  return null;
}

/** Packs shown in the sticker panel tabs (installed / custom only — no emoji builtins). */
export function getAllStickerPacks() {
  const installedIds = new Set(loadInstalledPackIds());
  // Remote packs only appear when installed; local-only custom packs always show.
  const custom = loadCustomStickerPacks().filter((p) => {
    if (!(p.stickers || []).length) return false;
    if (p.remote) return installedIds.has(String(p.id));
    return true;
  });
  const packs = [...custom];
  const order = loadPackOrder();
  if (!order.length) return packs;
  const byId = new Map(packs.map((p) => [String(p.id), p]));
  const ordered = [];
  for (const id of order) {
    const p = byId.get(String(id));
    if (p) {
      ordered.push(p);
      byId.delete(String(id));
    }
  }
  for (const p of byId.values()) ordered.push(p);
  return ordered;
}

function packsForLookup() {
  return [...loadCustomStickerPacks(), ...BUILTIN_STICKER_PACKS];
}

export function isBuiltinEmojiSticker(stickerId, packId) {
  const pid = packId != null ? String(packId) : '';
  if (pid && BUILTIN_STICKER_PACKS.some((p) => String(p.id) === pid)) return true;
  if (!stickerId) return false;
  const id = String(stickerId);
  return BUILTIN_STICKER_PACKS.some((p) => (p.stickers || []).some((s) => String(s.id) === id));
}

export function findStickerById(stickerId) {
  if (!stickerId) return null;
  for (const pack of packsForLookup()) {
    const hit = (pack.stickers || []).find((s) => s.id === stickerId);
    if (hit) {
      return {
        ...hit,
        packId: pack.id,
        packTitle: pack.title,
        packTitleFa: pack.titleFa,
        packIcon: pack.icon,
        packCustom: !!pack.custom,
      };
    }
  }
  return null;
}

export function packTitleLocalized(pack, locale = 'fa') {
  if (!pack) return '';
  const loc = String(locale || 'fa').toLowerCase();
  if ((loc.startsWith('fa') || loc.startsWith('ar')) && pack.titleFa) return pack.titleFa;
  return pack.title || pack.id;
}

export function setPackIcon(packId, icon) {
  if (!packId || !icon) return false;
  const packs = loadCustomStickerPacks();
  const pack = packs.find((p) => p.id === packId);
  if (!pack) return false;
  pack.icon = String(icon);
  saveCustomStickerPacks(packs);
  return true;
}

export function setStickerEmoji(packId, stickerId, emoji) {
  return updateCustomSticker(packId, stickerId, { emoji: emoji || '⭐' });
}

function normalizeEmojiKey(emoji) {
  return String(emoji || '')
    .replace(/\uFE0F/g, '')
    .trim();
}

/** Stickers whose emoji association matches (composer suggest strip). */
export function findStickersByEmoji(emoji) {
  const needle = normalizeEmojiKey(emoji);
  if (!needle) return [];
  const out = [];
  const seen = new Set();
  for (const pack of getAllStickerPacks()) {
    for (const st of pack.stickers || []) {
      if (normalizeEmojiKey(st.emoji) !== needle) continue;
      const id = st.id || `${pack.id}_${st.emoji}`;
      if (seen.has(id)) continue;
      seen.add(id);
      out.push({
        ...st,
        id,
        packId: pack.id,
        packCustom: !!pack.custom,
        packIcon: pack.icon,
        kind: st.kind || (st.src ? 'image' : 'emoji'),
      });
    }
  }
  return out.slice(0, 40);
}

/**
 * Merge server packs into local custom store (static URLs).
 * @param {object[]} serverPacks
 * @param {{ preferLocalSrc?: boolean, installIds?: string[]|null, markInstalled?: boolean }} [opts]
 * - installIds: when provided (from list API), sync installed remote ids to this list
 * - markInstalled: when true (default) and installIds omitted, add these packs as installed
 * - markInstalled false: cache pack data for preview without installing
 */
export function mergeServerPacks(serverPacks = [], { preferLocalSrc = true, installIds = null, markInstalled = true } = {}) {
  if (!Array.isArray(serverPacks) || !serverPacks.length) return;
  const existing = loadCustomStickerPacks();
  const localOnly = existing.filter((p) => !p.remote);
  const prevById = new Map(existing.map((p) => [String(p.id), p]));

  const remote = serverPacks.map((p) => {
    const prev = prevById.get(String(p.id));
    const prevStickers = prev?.stickers || [];
    const prevSrcById = new Map(prevStickers.map((s) => [String(s.id), s.src || null]));
    // Local data: previews whose ids disappeared after server replace (cu_ → uuid).
    const orphanDataSrcs = prevStickers
      .filter((s) => s.src && String(s.src).startsWith('data:'))
      .map((s) => ({ src: s.src, emoji: normalizeEmojiKey(s.emoji), id: String(s.id) }));

    const stickers = (p.stickers || []).map((s) => {
      let src = s.src || s.url || null;
      const localSrc = prevSrcById.get(String(s.id)) || null;
      if (preferLocalSrc && localSrc && String(localSrc).startsWith('data:')) {
        src = localSrc;
      } else if (!src || !String(src).trim()) {
        src = localSrc;
      }
      if (preferLocalSrc && (!src || !String(src).startsWith('data:'))) {
        const orphanIdx = orphanDataSrcs.findIndex((o) => !prevSrcById.has(String(s.id))
          && (!o.emoji || o.emoji === normalizeEmojiKey(s.emoji)));
        if (orphanIdx >= 0) {
          src = orphanDataSrcs[orphanIdx].src;
          orphanDataSrcs.splice(orphanIdx, 1);
        }
      }
      return {
        id: s.id,
        kind: s.kind || (src ? 'image' : 'emoji'),
        src,
        emoji: s.emoji || '⭐',
        mediaId: s.mediaId || s.media_id || null,
        width: s.width || null,
        height: s.height || null,
      };
    });
    return {
      id: p.id,
      title: p.title,
      titleFa: p.titleFa || p.title,
      icon: p.icon || '⭐',
      custom: !!p.custom,
      remote: true,
      stickers,
    };
  });

  const remoteIds = new Set(remote.map((p) => String(p.id)));
  const byId = new Map();
  // Keep previously cached remote packs that aren't in this batch (e.g. preview-only).
  existing.filter((p) => p.remote && !remoteIds.has(String(p.id))).forEach((p) => {
    byId.set(String(p.id), p);
  });
  [...remote, ...localOnly.filter((p) => !remoteIds.has(String(p.id)))].forEach((p) => {
    if (!byId.has(String(p.id))) byId.set(String(p.id), p);
  });
  saveCustomStickerPacks([...byId.values()]);

  if (Array.isArray(installIds)) {
    const installedSet = new Set(installIds.map(String));
    const keepLocal = loadInstalledPackIds().filter((id) => !remoteIds.has(String(id)) && !isServerPackId(id));
    // Also keep previously installed remote packs that weren't in this response batch.
    const keepOtherRemote = loadInstalledPackIds().filter((id) => (
      isServerPackId(id) && !remoteIds.has(String(id))
    ));
    saveInstalledPackIds([...keepLocal, ...keepOtherRemote, ...installedSet]);
  } else if (markInstalled) {
    saveInstalledPackIds([
      ...loadInstalledPackIds(),
      ...remote.map((p) => String(p.id)),
    ]);
  }
}

/** Cache a server pack for preview without marking it installed. */
export function cacheServerPack(serverPack) {
  if (!serverPack?.id) return;
  mergeServerPacks([serverPack], { markInstalled: false, preferLocalSrc: true });
}

/**
 * After adding a sticker, ensure the pack shows the new image immediately
 * (even before CDN URL is ready).
 */
export function ensurePackStickerPreview(packId, dataUrl, emoji = '⭐', serverPack = null) {
  if (!packId || !dataUrl) return;
  if (serverPack) mergeServerPacks([serverPack], { preferLocalSrc: true });
  const packs = loadCustomStickerPacks();
  const pack = packs.find((p) => p.id === packId || p.id === serverPack?.id);
  if (!pack) {
    addStickerToPack(packId, dataUrl, emoji);
    return;
  }
  const emojiKey = normalizeEmojiKey(emoji);
  let target = (pack.stickers || []).find((s) => s.src === dataUrl);
  if (!target) {
    target = (pack.stickers || []).find((s) => !s.src)
      || (pack.stickers || []).find((s) => normalizeEmojiKey(s.emoji) === emojiKey)
      || (pack.stickers || [])[0];
  }
  if (target) {
    target.src = dataUrl;
    target.kind = 'image';
    if (emoji) target.emoji = emoji;
  } else {
    pack.stickers = [{
      id: `cu_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`,
      kind: 'image',
      src: dataUrl,
      emoji: emoji || '⭐',
    }, ...(pack.stickers || [])].slice(0, 120);
  }
  saveCustomStickerPacks(packs);
}

/** Replace a local draft pack id with the server pack after create. */
export function replaceLocalPackWithServer(localPackId, serverPack) {
  if (!serverPack?.id) return;
  const existing = loadCustomStickerPacks();
  const local = localPackId ? existing.find((p) => p.id === localPackId) : null;
  let next = existing.filter((p) => p.id !== localPackId);
  // Park local stickers under the server id so merge can keep data: previews.
  if (local?.stickers?.length) {
    next = next.filter((p) => p.id !== serverPack.id);
    next.push({
      ...local,
      id: serverPack.id,
      remote: true,
      custom: true,
    });
  }
  saveCustomStickerPacks(next);
  mergeServerPacks([serverPack], { preferLocalSrc: true });
}
